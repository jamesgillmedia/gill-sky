#!/usr/bin/env python3
"""Build js/filmdata.js for the Film chapter player (js/filmplayer.js).
Everything comes from existing data: data.json (titles, role, meta, poster, previews, Vimeo url),
the r9-style pages film/{slug}/index.html (stills, short pager names), the reel's shots.json,
and tools/vimeo_ar.json (each Vimeo film's own width/height, read from Vimeo oEmbed).
Run from u4-opus-m4/:  python3 tools/film_player.py  [--refresh-vimeo]"""
import json, os, re, sys, html, urllib.request
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
data = json.load(open('data.json'))
cards = [c for c in data['chapters'] if c['k'] == 'film'][0]['cards']
AR = 'tools/vimeo_ar.json'
ar = json.load(open(AR)) if os.path.exists(AR) else {}

def vimeo_id(u):
    m = re.match(r'https?://(?:www\.)?vimeo\.com/(\d+)', u or '')
    return m.group(1) if m else None

need = [vimeo_id(c['media'].get('url')) for c in cards]
for vid in [v for v in need if v and (v not in ar or '--refresh-vimeo' in sys.argv)]:
    with urllib.request.urlopen('https://vimeo.com/api/oembed.json?url=https://vimeo.com/' + vid, timeout=20) as r:
        o = json.load(r)
    ar[vid] = {'w': o['width'], 'h': o['height'], 'title': o['title'], 'dur': o.get('duration')}
json.dump(ar, open(AR, 'w'), indent=1, ensure_ascii=False)

short = {}   # slug -> the short name r9's pagers use for it
pages = {}
for c in cards:
    p = 'film/%s/index.html' % c['slug']
    if not os.path.exists(p):
        continue
    s = open(p).read()
    pages[c['slug']] = s
    for href, txt in re.findall(r'<a class="(?:prev|next)" href="\.\./([^/]+)/">([^<]+)</a>', s):
        short[href] = html.unescape(txt).replace('\u2039', '').replace('\u203a', '').strip()

def page_stills(slug):
    s = pages.get(slug, '')
    out = []
    for blk in re.findall(r'<ol class="frames">(.*?)</ol>', s, re.S) + re.findall(r'<div class="stills"[^>]*>(.*?)</div>', s, re.S):
        for src in re.findall(r'<img src="([^"]+)"', blk):
            src = html.unescape(src).replace('../../', '', 1)
            if src not in out and os.path.exists(src):
                out.append(src)
    return out

films = []
for c in cards:
    if c.get('kind') != 'film':
        continue          # the Demo Reel (kind reel) keeps its own moving filmstrip
    m = c['media']
    slug = c['slug']
    f = {'s': slug, 'id': c['id'], 't': c['title'], 'role': c.get('role') or '', 'meta': c.get('meta') or '',
         'short': short.get(slug, ''), 'poster': m.get('big') or m.get('thumb') or '',
         'pv': m.get('pv') or '', 'sc': m.get('clip') or '', 'stills': page_stills(slug),
         'page': 'film/%s/' % slug if slug in pages else '', 'play': None}
    if f['pv'] == f['sc']:
        f['sc'] = ''
    vid = vimeo_id(m.get('url'))
    if slug == 'reel-2026':
        sh = json.load(open('media/v3/media/reel/shots.json'))
        f['play'] = {'type': 'native', 'src': sh['src720'], 'poster': sh['poster'], 'ar': round(1280 / 720, 4),
                     'shots': [{'t': x['t'], 'th': x['th'], 'title': x['title']} for x in sh['shots']]}
    elif vid:
        a = ar[vid]
        f['play'] = {'type': 'vimeo', 'id': vid, 'ar': round(a['w'] / a['h'], 4)}
    films.append(f)

js = ('/* generated by tools/film_player.py from data.json, film/{slug}/ pages, media/v3/media/reel/shots.json and '
      'tools/vimeo_ar.json. Do not edit by hand. */\nwindow.GJ_FILMS=' + json.dumps(films, ensure_ascii=False, separators=(',', ':')) + ';\n')
open('js/filmdata.js', 'w').write(js)
for f in films:
    p = f['play']
    print('%-34s %-7s stills=%2d idle=%s %s' % (f['s'], p['type'] if p else 'NONE', len(f['stills']),
          'pv' if f['pv'] else ('sc' if f['sc'] else 'still'), '' if f['page'] else 'NO PAGE'))
print(len(films), 'films')
